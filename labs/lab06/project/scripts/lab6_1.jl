# # Модель эпидемии. Случай 1: I(0) ≤ I*
# 
# **Вариант 60**
# 
# На одном острове вспыхнула эпидемия. Известно, что из всех проживающих на острове 
# (\(N=16548\)) в момент начала эпидемии (\(t=0\)) число заболевших людей 
# (являющихся распространителями инфекции) \(I(0)=208\). Число здоровых людей с иммунитетом 
# к болезни \(R(0)=48\). Число людей восприимчивых к болезни, но пока здоровых, 
# в начальный момент времени \(S(0)=N-I(0)-R(0)\).
# 
# Рассмотрим случай, когда \(I(0) \leq I^*\) (больные изолированы и не заражают здоровых).

using Plots
using DifferentialEquations

# ## Параметры модели

# Общая численность популяции
N = 16548

# Начальные условия
I0 = 208   # инфицированные особи
R0 = 48    # особи с иммунитетом
S0 = N - I0 - R0  # восприимчивые, но здоровые особи

# Коэффициенты
alpha = 0.01  # коэффициент заболеваемости
beta = 0.02   # коэффициент выздоровления

# ## Система дифференциальных уравнений для случая I(0) ≤ I*
# 
# Когда число заболевших не превышает критического значения \(I^*\), 
# все больные изолированы и не заражают здоровых:
# 
# \[
# \begin{cases}
# \frac{dS}{dt} = 0 \\
# \frac{dI}{dt} = -\beta I \\
# \frac{dR}{dt} = \beta I
# \end{cases}
# \]

function ode_fn_case1(du, u, p, t)
    S, I, R = u
    du[1] = 0          # dS/dt
    du[2] = -beta * I  # dI/dt
    du[3] = beta * I   # dR/dt
end

# ## Решение системы дифференциальных уравнений

# Начальные условия
v0 = [S0, I0, R0]

# Временной интервал
tspan = (0.0, 200.0)

# Создание и решение задачи
prob = ODEProblem(ode_fn_case1, v0, tspan)
sol = solve(prob, dtmax = 0.1)

# Извлечение результатов
S = [u[1] for u in sol.u]
I = [u[2] for u in sol.u]
R = [u[3] for u in sol.u]
T = [t for t in sol.t]

# ## Построение графиков

plt = plot(
    dpi = 300,
    legend = :topright,
    title = "Модель эпидемии: случай I(0) ≤ I*",
    xlabel = "Время t",
    ylabel = "Численность особей",
    linewidth = 2
)

plot!(
    plt,
    T,
    S,
    label = "Восприимчивые особи S(t)",
    color = :blue
)

plot!(
    plt,
    T,
    I,
    label = "Инфицированные особи I(t)",
    color = :green
)

plot!(
    plt,
    T,
    R,
    label = "Особи с иммунитетом R(t)",
    color = :red
)

# Сохранение графика в папку plots/lab6
mkpath("plots/lab6")
savefig(plt, "plots/lab6/lab6_case1.png")

